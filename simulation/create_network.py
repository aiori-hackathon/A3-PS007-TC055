"""
create_network.py - Linux Network Namespaces & Bridge Configuration for PS-007
Privacy-Aware IPv6 IoT Security Monitoring Across Address Rotation

Provides automated topology creation for Ubuntu ARM64 (UTM) Linux environments:
- Linux Bridge: br-iot0 (IPv6: 2001:db8:1::1/64)
- Network Namespaces:
    ns-mon      -> Monitoring Station (veth-mon)
    ns-iot1     -> Smart Camera (2001:db8:1::101/64)
    ns-iot2     -> Smart TV (2001:db8:1::102/64)
    ns-iot3     -> Smart Bulb (2001:db8:1::103/64)
    ns-iot4     -> Smart Speaker (2001:db8:1::104/64)
    ns-iot5     -> Smart Door Sensor (2001:db8:1::105/64)
    ns-attacker -> Security Attack Node (2001:db8:1::bad:1/64)

On macOS / Non-Linux environments:
- Detects the OS and generates a companion 'setup_linux_netns.sh' shell script.
- Explains that the Python monitor uses its Scapy pipeline simulation mode.
"""

import os
import sys
import platform
import subprocess
from typing import List, Tuple

BRIDGE_NAME = "br-iot0"
BRIDGE_IPV6 = "2001:db8:1::1/64"

NAMESPACES = [
    ("ns-mon", "veth-mon", "veth-br-mon", "2001:db8:1::2/64"),
    ("ns-iot1", "veth-iot1", "veth-br-iot1", "2001:db8:1::101/64"),
    ("ns-iot2", "veth-iot2", "veth-br-iot2", "2001:db8:1::102/64"),
    ("ns-iot3", "veth-iot3", "veth-br-iot3", "2001:db8:1::103/64"),
    ("ns-iot4", "veth-iot4", "veth-br-iot4", "2001:db8:1::104/64"),
    ("ns-iot5", "veth-iot5", "veth-br-iot5", "2001:db8:1::105/64"),
    ("ns-attacker", "veth-atk", "veth-br-atk", "2001:db8:1::bad:1/64")
]

def generate_bash_script(filepath: str = "setup_linux_netns.sh") -> None:
    """Generate shell script for setting up Linux namespaces and bridge."""
    lines = [
        "#!/usr/bin/env bash",
        "# setup_linux_netns.sh - Generated by PS-007 Network Creator",
        "# Run with: sudo bash setup_linux_netns.sh",
        "set -e",
        "",
        "echo '[+] Enabling IPv6 forwarding...'",
        "sysctl -w net.ipv6.conf.all.forwarding=1",
        "",
        f"echo '[+] Creating Linux Bridge {BRIDGE_NAME}...'",
        f"ip link add name {BRIDGE_NAME} type bridge || true",
        f"ip link set {BRIDGE_NAME} up",
        f"ip -6 addr add {BRIDGE_IPV6} dev {BRIDGE_NAME} || true",
        ""
    ]

    for ns, veth_ns, veth_br, ipv6 in NAMESPACES:
        lines.extend([
            f"echo '[+] Setting up {ns}...'",
            f"ip netns add {ns} || true",
            f"ip link add {veth_ns} type veth peer name {veth_br} || true",
            f"ip link set {veth_ns} netns {ns}",
            f"ip link set {veth_br} master {BRIDGE_NAME}",
            f"ip link set {veth_br} up",
            f"ip netns exec {ns} ip link set lo up",
            f"ip netns exec {ns} ip link set {veth_ns} up",
            f"ip netns exec {ns} ip -6 addr add {ipv6} dev {veth_ns} || true",
            ""
        ])

    lines.extend([
        "echo '[SUCCESS] IPv6 IoT Isolated Virtual Network Created!'",
        f"echo '[*] Bridge: {BRIDGE_NAME} with IPv6: {BRIDGE_IPV6}'",
        "echo '[*] Namespaces: ns-mon, ns-iot1..ns-iot5, ns-attacker'",
        "echo '[*] To run Scapy monitor in monitor namespace: sudo ip netns exec ns-mon python3 backend/app.py'"
    ])

    script_content = "\n".join(lines) + "\n"
    with open(filepath, "w") as f:
        f.write(script_content)
    os.chmod(filepath, 0o755)

def generate_teardown_script(filepath: str = "teardown_linux_netns.sh") -> None:
    """Generate teardown script for Linux namespaces."""
    lines = [
        "#!/usr/bin/env bash",
        "# teardown_linux_netns.sh - Generated by PS-007",
        "# Run with: sudo bash teardown_linux_netns.sh",
        "",
        f"echo '[-] Removing bridge {BRIDGE_NAME}...'",
        f"ip link set {BRIDGE_NAME} down 2>/dev/null || true",
        f"ip link delete {BRIDGE_NAME} type bridge 2>/dev/null || true",
        ""
    ]

    for ns, _, _, _ in NAMESPACES:
        lines.append(f"ip netns delete {ns} 2>/dev/null || true")

    lines.append("echo '[+] All namespaces and bridges removed.'\n")
    with open(filepath, "w") as f:
        f.write("\n".join(lines))
    os.chmod(filepath, 0o755)

def run_linux_setup() -> bool:
    """Attempt direct execution if running as root on Linux."""
    if platform.system() != "Linux":
        print(f"[*] Detected Host OS: {platform.system()}")
        print("[*] Linux Network Namespaces & veth pairs require an Ubuntu/Linux kernel.")
        print("[*] Generating 'setup_linux_netns.sh' and 'teardown_linux_netns.sh' for your Ubuntu ARM64 (UTM) VM.")
        generate_bash_script("setup_linux_netns.sh")
        generate_teardown_script("teardown_linux_netns.sh")
        print("[+] Generated: setup_linux_netns.sh & teardown_linux_netns.sh")
        print("[*] The system will automatically run in Safe Simulation Mode on this Mac host.")
        return False

    if os.geteuid() != 0:
        print("[!] Root privileges (sudo) required to create network namespaces.")
        generate_bash_script("setup_linux_netns.sh")
        generate_teardown_script("teardown_linux_netns.sh")
        return False

    print("[+] Configuring Linux Bridge and Namespaces natively...")
    generate_bash_script("/tmp/setup_netns_temp.sh")
    subprocess.run(["bash", "/tmp/setup_netns_temp.sh"], check=True)
    return True

if __name__ == "__main__":
    run_linux_setup()

